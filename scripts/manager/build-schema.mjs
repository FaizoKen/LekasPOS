// Writes site/manager/js/schema.js: the app's database schema (the latest snapshot in
// app/src/androidTest/assets/schemas/, the DDL of Schema.kt) for the manager web page, which keeps its
// copy of the shop in the same tables. The full-text table is left out (the web page's SQLite has no
// FTS4). Run after every schema change: node scripts/manager/build-schema.mjs
// `node --test scripts/manager/` fails while schema.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

/** The schema version of Schema.kt (`const val VERSION = n`). */
export function appVersion() {
  const kt = readFileSync(join(root, 'app/src/main/java/com/lekaspos/data/db/Schema.kt'), 'utf8');
  const m = /const val VERSION = (\d+)/.exec(kt);
  if (!m) throw new Error('VERSION not found in Schema.kt');
  return Number(m[1]);
}

export function render() {
  const version = appVersion();
  const sql = readFileSync(join(root, `app/src/androidTest/assets/schemas/${version}.sql`), 'utf8');
  const statements = sql.split(';\n').map((s) => s.trim().replace(/;$/, '')).filter(Boolean)
    .filter((s) => !/^CREATE VIRTUAL TABLE/i.test(s));
  return '// Generated by scripts/manager/build-schema.mjs from app/src/androidTest/assets/schemas/' +
    `${version}.sql — do not edit.\n` +
    '// The app\'s tables (Schema.kt) without the full-text table product_fts.\n\n' +
    `export const APP_SCHEMA = ${version};\n\n` +
    'export const STATEMENTS = [\n' +
    statements.map((s) => `  ${JSON.stringify(s)},`).join('\n') +
    '\n];\n';
}

export const OUT = join(root, 'site/manager/js/schema.js');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUT, render());
  console.log(`site/manager/js/schema.js: schema ${appVersion()}`);
}
