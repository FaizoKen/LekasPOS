let lang = 'en';

export function setLanguage(l) {
  lang = l === 'ms' ? 'ms' : 'en';
  document.documentElement.lang = lang;
}

export const language = () => lang;

/** The text of [key] in the page's language, with %1$s / %1$d / %s / %d filled from [args]. */
export function t(key, ...args) {
  const s = WEB[lang][key] ?? APP_STRINGS[lang][key] ?? WEB.en[key] ?? APP_STRINGS.en[key] ?? key;
  let next = 0;
  return s.replace(/%(?:(\d+)\$)?([sd])/g, (_, n, type) => {
    const v = args[n ? Number(n) - 1 : next++];
    return type === 'd' ? String(v ?? 0) : String(v ?? '');
  });
}

